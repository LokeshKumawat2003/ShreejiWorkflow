const { registerTool } = require('../assistantToolRegistry');

const DOCUMENT_TYPES = [
  'salary_slip',
  'payroll',
  'wage_register',
  'attendance_register',
];

function registerDocumentTools() {
  for (const type of DOCUMENT_TYPES) {
    registerTool({
      name: `document.generate.${type}`,
      description: `Prepare ${type} document download metadata. Actual PDF/Excel is generated by existing app exporters.`,
      mutates: false,
      roles: ['admin'],
      legacyPlanType: type,
      inputSchema: {
        month: { type: 'month', required: true },
        format: { type: 'format', default: 'pdf' },
        organizationId: { type: 'objectId' },
        locationId: { type: 'objectId' },
        employeeId: { type: 'objectId' },
        employeeIds: { type: 'objectIdArray' },
      },
      async execute({ args }) {
        return {
          legacyPlan: {
            type,
            month: args.month,
            format: args.format || 'pdf',
            organizationId: args.organizationId || null,
            locationId: args.locationId || null,
            employeeId: args.employeeId || null,
            employeeIds: args.employeeIds || null,
          },
          previewOnly: false,
        };
      },
    });
  }

  registerTool({
    name: 'document.generateSalarySlip',
    description: 'Generate salary slip download for employee(s).',
    mutates: false,
    roles: ['admin'],
    legacyPlanType: 'salary_slip',
    inputSchema: {
      month: { type: 'month', required: true },
      format: { type: 'format', default: 'pdf' },
      organizationId: { type: 'objectId' },
      locationId: { type: 'objectId' },
      employeeId: { type: 'objectId' },
      employeeIds: { type: 'objectIdArray' },
    },
    async execute({ args }) {
      return {
        legacyPlan: {
          type: 'salary_slip',
          month: args.month,
          format: args.format || 'pdf',
          organizationId: args.organizationId || null,
          locationId: args.locationId || null,
          employeeId: args.employeeId || null,
          employeeIds: args.employeeIds || null,
        },
      };
    },
  });
}

module.exports = { registerDocumentTools, DOCUMENT_TYPES };
